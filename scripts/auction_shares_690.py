#!/usr/bin/env python3
"""Compare the auction series before and after the SOMA exclusion (#690).

An exploratory measurement, not a record and not a verdict: nothing is selected and no published figure moves.
`before` is the screen of #630 as corrected for the carry cap (#680), `docs/pivot/evidence/new-sources-capped/screen.json`;
`after` is the same screen (`scripts/new_sources.py screen`, the same scratch panel, seeds and bootstraps) on the tree where
`new_sources.parse_auction_results` leaves the Fed's rollover (SOMA) out of the dealer and indirect shares and of the cover.
Only the three columns that changed differ between the two screens; every other series is identical.

    PYTHONPATH=src python3 scripts/new_sources.py panel --panel SCREEN.csv --output NEW.csv
    PYTHONPATH=src python3 scripts/new_sources.py screen --panel NEW.csv --output AFTER
    python3 scripts/auction_shares_690.py --extract AFTER/screen.json docs/pivot/evidence/auction-shares/screen_subset.json
    python3 scripts/auction_shares_690.py --compare docs/pivot/evidence/new-sources-capped/screen.json \\
        docs/pivot/evidence/auction-shares/screen_subset.json --output docs/pivot/evidence/auction-shares/comparison.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SERIES = ("auc_dealer_share", "auc_cover", "auc_indirect_share")
LEADS = ("1", "2", "3", "5", "10")
SPLITS = (("ordinary", "ordinary days"), ("band:scarce", "scarce band"), ("band:ample", "ample band"))


def _fmt(value, spec="{:+.3f}"):
    return "n/a" if value is None else spec.format(value)


def _interval(pair):
    return "" if not pair else f" [{pair[0]:+.2f}, {pair[1]:+.2f}]"


def extract(source: Path, output: Path) -> None:
    full = json.loads(source.read_text())
    subset = {"scope": full["scope"], "series": {name: full["series"][name] for name in SERIES}}
    output.write_text(json.dumps(subset, indent=1, sort_keys=True) + "\n", encoding="utf-8")


def compare(before: dict, after: dict) -> str:
    lines = [
        "# Auction series with and without the Fed's rollover (SOMA) in the denominator (#690)",
        "",
        "Generated by `scripts/auction_shares_690.py`. Exploratory: not a record and not a verdict; the intervals are 90 % bootstrap",
        "intervals that resample days independently and are too narrow, and they are written only at leads 1 and 5 (`n/a` elsewhere).",
        "An AUROC is `n/a` where a split has fewer pressure days than the screen's minimum. `before` divides by the total accepted",
        "(#630 as published); `after` divides by the accepted amount outside SOMA and, for the cover, uses Treasury's definition.",
        "",
        "## Partial rank correlation with the pressure indicator, ordinary days (the scarcity state and the as-of tail spread taken out)",
        "",
        "| series | before: partial rho [90 %] | after: partial rho [90 %] | before: raw rho | after: raw rho | before: n | after: n |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in SERIES:
        b = before["series"][name]["partial"]
        a = after["series"][name]["partial"]
        lines.append(
            f"| `{name}` | {_fmt(b['pressure']['partial'])}{_interval(b['pressure'].get('interval'))} | "
            f"{_fmt(a['pressure']['partial'])}{_interval(a['pressure'].get('interval'))} | "
            f"{_fmt(b['pressure']['raw'])} | {_fmt(a['pressure']['raw'])} | {b['n']} | {a['n']} |"
        )
    for key, label in SPLITS:
        lines += [
            "",
            f"## AUROC of the +5 bp indicator, {label}, by lead",
            "",
            "| series | lead | before: AUROC [90 %] | before: n (pressure days) | after: AUROC [90 %] | after: n (pressure days) |",
            "|---|---|---|---|---|---|",
        ]
        for name in SERIES:
            for lead in LEADS:
                b = before["series"][name]["leads"][lead][key]["auroc"]
                a = after["series"][name]["leads"][lead][key]["auroc"]
                lines.append(
                    f"| `{name}` | {lead} | {_fmt(b['auroc'], '{:.3f}')}{_interval(b.get('interval'))} | {b['n']} ({b['pressure_days']}) | "
                    f"{_fmt(a['auroc'], '{:.3f}')}{_interval(a.get('interval'))} | {a['n']} ({a['pressure_days']}) |"
                )
    lines += [
        "",
        "## Pre-onset contrast at lead 1 (the six onsets on ordinary days)",
        "",
        "| series | before: AUC [90 %] | after: AUC [90 %] |",
        "|---|---|---|",
    ]
    for name in SERIES:
        b = before["series"][name]["pre_onset"]["ordinary"]
        a = after["series"][name]["pre_onset"]["ordinary"]
        lines.append(
            f"| `{name}` | {_fmt(b['auc'], '{:.3f}')}{_interval(b.get('auc_interval'))} | "
            f"{_fmt(a['auc'], '{:.3f}')}{_interval(a.get('auc_interval'))} |"
        )
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--extract", nargs=2, type=Path, metavar=("FULL", "SUBSET"))
    parser.add_argument("--compare", nargs=2, type=Path, metavar=("BEFORE", "AFTER"))
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    if args.extract:
        extract(*args.extract)
    if args.compare:
        text = compare(*(json.loads(p.read_text()) for p in args.compare))
        if args.output:
            args.output.write_text(text, encoding="utf-8")
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
