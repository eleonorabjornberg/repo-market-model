#!/usr/bin/env python3
"""Exposure of H5's labels to a SOFR revision, by revision size (#1019; corrects the wording of #940).

    PYTHONPATH=src python3 scripts/sofr_revision_exposure_1019.py
    PYTHONPATH=src python3 scripts/sofr_revision_exposure_1019.py --check

Development data, not a verdict. Serves H5 groundwork (#940). `scripts/sofr_revisions_940.py` counted the days with
`tau - 1 <= s <= tau + 2` and called the count an upper bound. That window is the reach of the smallest revision the
New York Fed makes (2 bp, since it revises only a change of more than one basis point and SOFR is quoted to the basis
point). A larger revision reaches further, so the count is the days a 2 bp revision could flip, not a bound.

A revision of `m` bp moves the whole-bp spread `s` by `m`. Revised up from `s <= tau` the day is above `tau` when
`s + m > tau`; revised down from `s > tau` it is at or below when `s - m <= tau`. So the day can flip exactly when
`tau - m + 1 <= s <= tau + m` (`flip_window`). The window of a smaller revision lies inside that of a larger one,
so the counts by size are nested.

It reads the same tracked inputs as `sofr_revisions_940.py` (reusing its checked loaders) and the same days, on or
before 2025-12-31 (`docs/decisions/lockbox.md`). It says nothing about how many days were revised: none can be shown.
Writes `docs/research/sofr-revision-exposure-1019/result.json` and `docs/research/sofr-revision-exposure-1019-result.md`.

Stdlib only.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from repo_model.data import exceeds_bp  # noqa: E402

SIZES = (2, 3, 5, 10)
OUT_JSON = REPO / "docs" / "research" / "sofr-revision-exposure-1019" / "result.json"
OUT_MD = REPO / "docs" / "research" / "sofr-revision-exposure-1019-result.md"


def _original():
    spec = importlib.util.spec_from_file_location("sofr_revisions_940_script", REPO / "scripts" / "sofr_revisions_940.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def flip_window(tau: int, size: int) -> tuple[int, int]:
    """Inclusive range of whole-bp spreads whose label at `tau` a revision of `size` bp could flip."""
    if size < 2:
        raise ValueError(f"the New York Fed revises only a change of more than 1 bp; got {size}")
    return tau - size + 1, tau + size


def build():
    base = _original()
    _, rows = base._snapshot()
    iorb = base._iorb_rows()
    spreads = []
    for r in rows:
        day = date.fromisoformat(r["effectiveDate"])
        if base.FIRST_DAY <= day <= base.LAST_DAY:
            spreads.append(round((float(r["percentRate"]) - base._iorb_on(iorb, day)) * 100))
    exposure = {}
    for tau in base.THRESHOLDS:
        by_size, window = {}, {}
        for size in SIZES:
            lo, hi = flip_window(tau, size)
            by_size[str(size)] = sum(1 for s in spreads if lo <= s <= hi)
            window[str(size)] = [lo, hi]
        exposure[f"+{tau}"] = {
            "days_above": sum(1 for s in spreads if exceeds_bp(s, tau)),
            "window_bp": window,
            "by_size": by_size,
        }
    return {
        "status": "development data, not a verdict",
        "directive": "eleonorabjornberg/repo-market-model#1019",
        "serves": "H5 groundwork (#940)",
        "vintage": "current vintage",
        "window": {"first": base.FIRST_DAY.isoformat(), "last": base.LAST_DAY.isoformat(), "days": len(spreads)},
        "sizes_bp": list(SIZES),
        "dates_flagged_revised": 0,
        "exposure": exposure,
    }


def render(result):
    lines = [
        "# SOFR revision exposure by revision size (#1019)",
        "",
        "**Development data, not a verdict.** Generated by `python3 scripts/sofr_revision_exposure_1019.py`; never",
        "hand-edited. Serves H5 groundwork (#940). Figures are **current vintage**. This page corrects a wording in",
        "[`sofr-revisions-940.md`](sofr-revisions-940.md), which stands unchanged apart from a pointer here.",
        "",
        "## The correction",
        "",
        "The earlier page called its count of days with spread `s` in `[tau - 1, tau + 2]` an \"upper bound\". It is not.",
        "The New York Fed revises only a change of more than one basis point and SOFR is quoted to the basis point, so",
        "the smallest revision is 2 bp, and that window is its reach. A revision of `m` bp can flip a day's label at",
        "`tau` exactly when `tau - m + 1 <= s <= tau + m`. A larger revision reaches further; the earlier count is the",
        "number of days a 2 bp revision could flip.",
        "",
        "## Exposure by revision size",
        "",
        f"Days {result['window']['first']} to {result['window']['last']} ({result['window']['days']} days with a SOFR row;",
        "`docs/decisions/lockbox.md` locks every later day). Spread = SOFR less the IOER or IORB in force that day, on",
        "whole basis points; above a threshold when strictly above it. Each cell is the number of days whose label at",
        "that threshold a revision of that size could flip, if one happened on that day. A smaller revision's window lies",
        "inside a larger one's, so the counts rise along each row.",
        "",
        "| Threshold | Days above | Days a 2 bp revision could flip | 3 bp | 5 bp | 10 bp |",
        "|---|---|---|---|---|---|",
    ]
    for key, cell in result["exposure"].items():
        counts = " | ".join(str(cell["by_size"][str(m)]) for m in result["sizes_bp"])
        lines.append(f"| {key} bp | {cell['days_above']} | {counts} |")
    lines += [
        "",
        "Windows of spread (bp, inclusive) behind each cell:",
        "",
        "| Threshold | 2 bp | 3 bp | 5 bp | 10 bp |",
        "|---|---|---|---|---|",
    ]
    for key, cell in result["exposure"].items():
        windows = " | ".join(f"[{cell['window_bp'][str(m)][0]}, {cell['window_bp'][str(m)][1]}]" for m in result["sizes_bp"])
        lines.append(f"| {key} bp | {windows} |")
    lines += [
        "",
        "## What this does and does not show",
        "",
        "- It is exposure, not an effect. The API's `revisionIndicator` is blank on every row, so no date can be shown to",
        "  have been revised, and first prints for the past are not recoverable here (see the earlier page).",
        "- It does not say how often a revision of each size happens, so the larger columns are reach, not likelihood.",
        "- It does not settle how a same-day revision is treated or which vintage is the outcome; that is Eleonora's.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare with the committed files; write nothing")
    args = parser.parse_args(argv)
    result = build()
    payload = json.dumps(result, indent=1, sort_keys=True) + "\n"
    page = render(result)
    if args.check:
        if not OUT_JSON.exists() or OUT_JSON.read_text(encoding="utf-8") != payload or OUT_MD.read_text(encoding="utf-8") != page:
            print("stale: run python3 scripts/sofr_revision_exposure_1019.py", file=sys.stderr)
            return 1
        print("ok")
        return 0
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(payload, encoding="utf-8")
    OUT_MD.write_text(page, encoding="utf-8")
    print(f"wrote {OUT_JSON.relative_to(REPO)} and {OUT_MD.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
