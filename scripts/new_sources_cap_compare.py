#!/usr/bin/env python3
"""Compare the screen of the dealer financing series with and without the 13-day carry cap (#680).

An exploratory measurement, not a record: nothing is selected and no published figure moves.
`UNCAPPED` is the screen of #630 re-run on the same scratch panel (run from a checkout of the commit before
#680: `scripts/new_sources.py panel` then `screen`), reduced to the two series below with `--extract`;
`CAPPED` is the same screen on the tree with the cap. The scratch panel is built as `scripts/source_screen.py` and
`scripts/new_sources.py` describe.

    python3 scripts/new_sources_cap_compare.py --extract UNCAPPED_FULL.json docs/pivot/evidence/new-sources-capped/uncapped_subset.json
    python3 scripts/new_sources_cap_compare.py --compare docs/pivot/evidence/new-sources-capped/uncapped_subset.json \\
        docs/pivot/evidence/new-sources-capped/screen.json --output docs/pivot/evidence/new-sources-capped/comparison.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

SERIES = ("pd_repo_ust", "pd_reverse_repo_ust")
LEADS = ("1", "2", "3", "5", "10")


def _fmt(value, spec="{:+.3f}"):
    return "n/a" if value is None else spec.format(value)


def _interval(pair):
    return "" if not pair else f" [{pair[0]:+.2f}, {pair[1]:+.2f}]"


def extract(source: Path, output: Path) -> None:
    full = json.loads(source.read_text())
    subset = {"scope": full["scope"], "series": {name: full["series"][name] for name in SERIES}}
    output.write_text(json.dumps(subset, indent=1, sort_keys=True) + "\n", encoding="utf-8")


def compare(before: dict, after: dict) -> str:
    lines = [
        "# Dealer financing series, with and without the 13-day carry cap (#680)",
        "",
        "Generated by `scripts/new_sources_cap_compare.py`. Exploratory: not a record and not a verdict; the intervals are 90 % bootstrap",
        "intervals that resample days independently and are too narrow. `before` is #630's carry with no limit; `after` stops the carry 13 days",
        "after a value's as-of date (`data.WEEKLY_CARRY_MAX_STALENESS_DAYS`).",
        "",
        "## Partial rank correlation with the pressure indicator, ordinary days (the scarcity state and the tail spread taken out)",
        "",
        "| series | before: partial rho [90 %] | after: partial rho [90 %] | before: n | after: n |",
        "|---|---|---|---|---|",
    ]
    for name in SERIES:
        b = before["series"][name]["partial"]
        a = after["series"][name]["partial"]
        lines.append(
            f"| `{name}` | {_fmt(b['pressure']['partial'])}{_interval(b['pressure'].get('interval'))} | "
            f"{_fmt(a['pressure']['partial'])}{_interval(a['pressure'].get('interval'))} | {b['n']} | {a['n']} |"
        )
    lines += [
        "",
        "## AUROC of the +5 bp indicator, scarce band, by lead",
        "",
        "| series | lead | before: AUROC [90 %] | before: n (pressure days) | after: AUROC [90 %] | after: n (pressure days) |",
        "|---|---|---|---|---|---|",
    ]
    for name in SERIES:
        for lead in LEADS:
            b = before["series"][name]["leads"][lead]["band:scarce"]["auroc"]
            a = after["series"][name]["leads"][lead]["band:scarce"]["auroc"]
            lines.append(
                f"| `{name}` | {lead} | {_fmt(b['auroc'], '{:.3f}')}{_interval(b.get('interval'))} | {b['n']} ({b['pressure_days']}) | "
                f"{_fmt(a['auroc'], '{:.3f}')}{_interval(a.get('interval'))} | {a['n']} ({a['pressure_days']}) |"
            )
    lines += [
        "",
        "## AUROC of the +5 bp indicator, ordinary days, by lead",
        "",
        "| series | lead | before: AUROC [90 %] | before: n | after: AUROC [90 %] | after: n |",
        "|---|---|---|---|---|---|",
    ]
    for name in SERIES:
        for lead in LEADS:
            b = before["series"][name]["leads"][lead]["ordinary"]["auroc"]
            a = after["series"][name]["leads"][lead]["ordinary"]["auroc"]
            lines.append(
                f"| `{name}` | {lead} | {_fmt(b['auroc'], '{:.3f}')}{_interval(b.get('interval'))} | {b['n']} | "
                f"{_fmt(a['auroc'], '{:.3f}')}{_interval(a.get('interval'))} | {a['n']} |"
            )
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--extract", nargs=2, type=Path, metavar=("FULL", "SUBSET"))
    parser.add_argument("--compare", nargs=2, type=Path, metavar=("BEFORE", "AFTER"))
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    if args.extract:
        extract(*args.extract)
    if args.compare:
        text = compare(*(json.loads(p.read_text()) for p in args.compare))
        if args.output:
            args.output.write_text(text, encoding="utf-8")
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
